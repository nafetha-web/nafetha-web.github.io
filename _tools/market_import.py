#!/usr/bin/env python3
"""Excel/CSV -> data.js for a Nafetha supermarket client (same format as demo/khayrat/data.js).

Usage: python3 market_import.py products.xlsx <client_dir> [--areas "الاسم:رسوم,..."]
Columns (Arabic or English header, order does not matter):
  القسم | اسم المنتج | الاسم بالإنكليزي (اختياري) | الوحدة | السعر | السعر القديم (اختياري) | بالكيلو (نعم/لا) | صورة (اختياري)
"""
import sys, re, json, csv, os, argparse

H = {
  'cat': ['القسم', 'الصنف', 'التصنيف', 'category', 'cat', 'section'],
  'ar': ['اسم المنتج', 'المنتج', 'الاسم', 'الاسم بالعربي', 'name', 'name_ar', 'product'],
  'en': ['الاسم بالإنكليزي', 'الاسم بالانكليزي', 'الاسم بالإنجليزي', 'english', 'name_en'],
  'unit': ['الوحدة', 'unit', 'size', 'الحجم'],
  'price': ['السعر', 'price', 'السعر بالدولار', 'usd'],
  'old': ['السعر القديم', 'قبل الخصم', 'old', 'old_price'],
  'kg': ['بالكيلو', 'كيلو', 'kg', 'per_kg'],
  'img': ['صورة', 'الصورة', 'image', 'img'],
}

def norm(s):
    s = re.sub(r'\(.*?\)|[؟?]', '', str(s or '')).strip().lower().replace('أ', 'ا').replace('إ', 'ا').replace('ة', 'ه')
    return re.sub(r'[\s_\-]+', ' ', s).strip()

def colmap(header):
    m = {}
    for i, h in enumerate(header):
        for k, names in H.items():
            if k not in m and norm(h) in [norm(n) for n in names]:
                m[k] = i
    return m

def read_rows(path):
    if path.lower().endswith('.csv'):
        with open(path, encoding='utf-8-sig', newline='') as f:
            return [r for r in csv.reader(f)]
    import openpyxl
    ws = openpyxl.load_workbook(path, data_only=True).active
    return [[c if c is not None else '' for c in r] for r in ws.iter_rows(values_only=True)]

def num(v):
    s = str(v).strip().replace(',', '.').replace('$', '')
    s = s.translate(str.maketrans('٠١٢٣٤٥٦٧٨٩٫', '0123456789.'))
    try: return float(s)
    except ValueError: return None

def yes(v): return norm(v) in ('نعم', 'yes', 'y', '1', 'true', 'x', 'اي', 'ايه')

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('src'); ap.add_argument('out')
    ap.add_argument('--areas', default='')
    a = ap.parse_args()
    rows = read_rows(a.src)
    hi = next(i for i, r in enumerate(rows) if len(colmap(r)) >= 3)
    cm = colmap(rows[hi])
    for need in ('cat', 'ar', 'price'):
        if need not in cm: sys.exit('عمود ناقص: ' + need)
    cats, prods, bad, n = [], [], [], 0
    for ln, r in enumerate(rows[hi + 1:], hi + 2):
        g = lambda k: (str(r[cm[k]]).strip() if k in cm and cm[k] < len(r) else '')
        if not g('ar') and not g('price'): continue
        p = num(g('price'))
        if not g('ar') or not g('cat') or p is None or p <= 0:
            bad.append(f'سطر {ln}: ناقص اسم/قسم/سعر ({g("ar") or "؟"})'); continue
        ck = next((c['k'] for c in cats if norm(c['ar']) == norm(g('cat'))), None)
        if not ck:
            ck = 'c%d' % (len(cats) + 1); cats.append({'k': ck, 'ar': g('cat'), 'en': g('cat'), 'img': ''})
        n += 1
        prods.append({'id': 'p%d' % n, 'c': ck, 'ar': g('ar'), 'en': g('en') or g('ar'), 'uar': g('unit'), 'uen': g('unit'),
                      'p': p, 'old': num(g('old')) or 0, 'kg': yes(g('kg')), 'pop': False,
                      'img': g('img') and ('img/' + g('img')) or '', 'kw': ' '.join(filter(None, [g('ar'), g('en'), g('cat')]))})
    areas = [[x.split(':')[0], x.split(':')[0], num(x.split(':')[1]) or 0] for x in a.areas.split(',') if x.strip()]
    js = '/* Generated by market_import.py from %s */\nconst CATS = %s;\nconst P = %s;\nconst byId = Object.fromEntries(P.map((p) => [p.id, p]));\nconst AREAS = %s;\n' % (
        os.path.basename(a.src), json.dumps(cats, ensure_ascii=False, indent=1), json.dumps(prods, ensure_ascii=False), json.dumps(areas, ensure_ascii=False))
    os.makedirs(a.out, exist_ok=True)
    open(os.path.join(a.out, 'data.js'), 'w', encoding='utf-8').write(js)
    print(f'تم: {len(prods)} منتج، {len(cats)} قسم')
    for b in bad: print('تنبيه', b)

if __name__ == '__main__': main()
